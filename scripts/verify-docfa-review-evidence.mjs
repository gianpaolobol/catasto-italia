import {lstat,open} from 'node:fs/promises';
import {constants} from 'node:fs';
import {resolve,join} from 'node:path';
import {pathToFileURL} from 'node:url';
import {createHash} from 'node:crypto';
import {isDeepStrictEqual} from 'node:util';
import {readOfflineReviewRecords,summarizeOfflineReviews} from './summarize-docfa-reviews.mjs';

const MiB=1024*1024;
const canonical=x=>JSON.stringify(x,(_,v)=>v&&typeof v==='object'&&!Array.isArray(v)
  ?Object.fromEntries(Object.keys(v).sort().map(k=>[k,v[k]])):v);
const sha=x=>createHash('sha256').update(x).digest('hex');
const safeToken=x=>typeof x==='string'&&/^[a-z_]+$/.test(x);
const safeHash=x=>typeof x==='string'&&/^[0-9a-f]{64}$/.test(x);
const flags=constants.O_RDONLY|(constants.O_NOFOLLOW??0)|(constants.O_NONBLOCK??0);
const same=(a,b)=>a.isFile()&&b.isFile()&&a.dev===b.dev&&a.ino===b.ino&&
  a.size===b.size&&a.mtimeMs===b.mtimeMs&&a.ctimeMs===b.ctimeMs;
const warning='NON UFFICIALE — integrita dei byte, non autenticita, vigenza o validazione professionale.';
const exclusions={officialValidation:false,officialExport:false,signature:false,submission:false};
const fail=code=>{throw Error(code);};

// Only fixed, flat names generated by the program. No user-entered reference is dereferenced.
// Local directories must be quiescent during capture/verification; not an adversarial sandbox.
async function fingerprint(root,name,maxBytes,retain=false){
  const path=join(root,name), before=await lstat(path);
  if(!before.isFile()||before.size<1||before.size>maxBytes)throw Error('invalid_evidence_file');
  const handle=await open(path,flags);
  try{
    const start=await handle.stat();
    if(!same(before,start))fail('evidence_changed');
    const hash=createHash('sha256'),buffer=Buffer.alloc(64*1024),chunks=[];
    let used=0;
    for(;;){
      const length=Math.min(buffer.length,start.size+1-used);
      if(length<=0)fail('evidence_changed');
      const {bytesRead}=await handle.read(buffer,0,length,used);
      if(!bytesRead)break;
      used+=bytesRead;
      if(used>start.size)fail('evidence_changed');
      const part=buffer.subarray(0,bytesRead);
      hash.update(part);
      if(retain)chunks.push(Buffer.from(part));
    }
    if(used!==start.size||!same(start,await handle.stat())||!same(start,await lstat(path)))fail('evidence_changed');
    return {bytes:used,sha256:hash.digest('hex'),...(retain?{content:Buffer.concat(chunks)}:{})};
  }finally{await handle.close();}
}

export async function captureEvidenceManifest(directory){
  const root=resolve(directory);
  if(!(await lstat(root)).isDirectory())fail('review_directory_required');
  const records=await readOfflineReviewRecords(root),summary=summarizeOfflineReviews(records);
  if(summary.invalid||summary.unassessedChecks)fail('complete_declared_reviews_required');
  const archives=new Map(),checks=[],cases=[];
  for(const {scenario} of summary.cases){
    if(!safeToken(scenario))fail('unexpected_scenario');
    const record=records.get(scenario),archiveSha256=record.environment.archiveSha256;
    if(!safeHash(archiveSha256))fail('invalid_archive_hash');
    if(!archives.has(archiveSha256)){
      const name='archive-'+archiveSha256+'.bin';
      const actual=await fingerprint(root,name,256*MiB);
      if(actual.sha256!==archiveSha256)fail('archive_hash_mismatch');
      archives.set(archiveSha256,{name,...actual});
    }
    cases.push({scenario,snapshotDigest:record.snapshotDigest,
      recordDigest:sha(canonical(record)),archiveSha256});
    for(const observation of record.observations){
      if(!safeToken(observation.id))fail('unexpected_check_id');
      const name=scenario+'--'+observation.id+'.bin';
      if(observation.evidenceReference!==name)fail('fixed_evidence_reference_required');
      const actual=await fingerprint(root,name,64*MiB);
      checks.push({scenario,id:observation.id,state:observation.state,name,...actual});
    }
  }
  return {version:'0.1.0',kind:'synthetic-docfa-evidence-manifest',warning,
    expectedChecks:summary.expectedChecks,cases,archives:[...archives.values()],checks,
    differenceDeclared:summary.totals.difference_declared,
    notApplicableDeclared:summary.totals.not_applicable_declared,...exclusions};
}

export async function verifyEvidenceManifest(directory){
  const root=resolve(directory);
  if(!(await lstat(root)).isDirectory())fail('review_directory_required');
  const saved=await fingerprint(root,'evidence-manifest.json',256*1024,true);
  const expected=JSON.parse(new TextDecoder('utf-8',{fatal:true}).decode(saved.content));
  const actual=await captureEvidenceManifest(root);
  const integrityVerified=isDeepStrictEqual(expected,actual);
  return {version:'0.1.0',kind:'synthetic-docfa-evidence-integrity-report',warning,
    integrityVerified,expectedChecks:actual.expectedChecks,
    differenceDeclared:actual.differenceDeclared,notApplicableDeclared:actual.notApplicableDeclared,
    ...exclusions};
}

if(process.argv[1]&&pathToFileURL(resolve(process.argv[1])).href===import.meta.url){
  const [mode,directory]=process.argv.slice(2);
  if(process.argv.length!==4||!['--capture','--verify'].includes(mode)){
    console.error('Uso: node scripts/verify-docfa-review-evidence.mjs --capture|--verify <cartella-locale>');
    process.exitCode=2;
  }else try{
    const result=mode==='--capture'?await captureEvidenceManifest(directory):await verifyEvidenceManifest(directory);
    console.log(JSON.stringify(result,null,2));
    process.exitCode=mode==='--verify'&&!result.integrityVerified?1:0;
  }catch{
    console.error('Integrita non verificabile: controllare registri completi, riferimenti fissi, file e impronte.');
    process.exitCode=1;
  }
}
